'use strict';
// Mechanical file:// transport of the unchanged binary bake; no pose conversion.
const fs=require('node:fs'),path=require('node:path');
const dir=path.resolve(__dirname,'../art-source/blender/guardian-command-timing-v9');
const output=path.join(dir,'game-motion-file.js');
const content='/* Generated by tools/guardian-motion-file.cjs from game-motion.bin. */\n'+
 'window.KRGuardianBlenderV9Motion='+JSON.stringify(fs.readFileSync(path.join(dir,'game-motion.bin')).toString('base64'))+';\n';
if(process.argv.includes('--check')){
 if(!fs.existsSync(output)||fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n')!==content)throw Error('Guardian file transport is stale');
 console.log('GUARDIAN_FILE_TRANSPORT_OK');
}else{fs.writeFileSync(output,content);console.log('GUARDIAN_FILE_TRANSPORT_GENERATED');}
