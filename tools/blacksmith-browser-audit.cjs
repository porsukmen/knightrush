const {chromium}=require('playwright'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url'),path=require('node:path'),fs=require('node:fs');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>window.requestAnimationFrame=()=>0);
  await page.goto(pathToFileURL(path.resolve('KnightRush.html')).href);
  await page.waitForFunction(()=>document.querySelector('canvas')?.dataset.bootReady==='1');
  const run=code=>page.evaluate(code=>(0,eval)(code),code);
  const tap=async(x,y)=>{const p=await run(`({x:(${x}*viewScale+viewX)/renderDpr(),y:(${y}*viewScale+viewY)/renderDpr()})`);
   await page.touchscreen.tap(p.x,p.y);};
  const out=path.resolve('output/blacksmith');fs.mkdirSync(out,{recursive:true});
  const shot=async name=>{await run('render()');await page.screenshot({path:path.join(out,name+'.png')});};
  await run(`SFX.toggle();startJourneyWithSeed(647486904);gold=130;startBoss();setMode('boss');
    squire.present=true;boss.hp=0;defeatBoss();boss.stateT=2.6;updateBoss(.016);flashA=0;
    function smithBrowserRng(values){let i=0;return ()=>values[i++];}`);
  assert.equal(await run('mode'),'town');await tap(90,450);await run('updateTown(.4)');
  assert.equal(await run('mode'),'shop');assert.equal(await run('squire.present'),false);
  await shot('01-forge');
  await tap(400,460);assert.equal(await run('blacksmithShop.selected'),3);
  assert.equal(await run('blacksmithShop.phase'),'browse');
  await tap(79,455);assert.equal(await run('blacksmithShop.selected'),0);
  await run('blacksmithShop.random=smithBrowserRng([0,.9,.999])');await tap(240,690);
  assert.equal(await run('gold'),112);await tap(240,690);assert.equal(await run('gold'),112);
  const distance=await run('dist');
  await run('update(.95)');await shot('02-windup');
  await page.keyboard.press('Escape');assert.equal(await run('paused'),true);
  const clock=await run('blacksmithShop.clock');await run('updateBlacksmithShop(1)');
  assert.equal(await run('blacksmithShop.clock'),clock);
  await page.keyboard.press('Escape');assert.equal(await run('paused'),false);
  await run('update(1.65)');await shot('03-grey-reveal');
  assert.equal(await run('runSkills[0].evolutionDepth'),0);
  await tap(240,750);assert.equal(await run('mode'),'shop');
  await run('update(2)');await shot('04-legendary');
  assert.equal(await run('runSkills[0].evolutionRarity'),'LEGENDARY');
  assert.equal(await run('dist'),distance);
  await tap(240,690);await run('blacksmithShop.random=smithBrowserRng([0,0])');await tap(240,690);
  await run('update(5)');await shot('05-fail');
  assert.equal(await run('gold'),97);assert.equal(await run('runSkills[0].evolutionDepth'),1);
  await tap(240,690);
  await page.setViewportSize({width:480,height:800});await shot('06-after-fail');
  await tap(240,750);assert.equal(await run('mode'),'town');await tap(240,705);await tap(240,705);
  assert.deepEqual(await run('[mode,loop,biome,runSkills[0].evolutionRarity]'),['run',2,'forest','LEGENDARY']);
  await run('gold=0;openBlacksmithShop();');await tap(240,690);
  assert.equal(await run('blacksmithShop.phase'),'browse');assert.equal(await run('gold'),0);
  await page.setViewportSize({width:780,height:1300});await run('resize();perfNow=1.2');
  await shot('07-bastion-large');
  await page.screenshot({path:path.join(out,'08-bastion-workshop.png'),clip:{x:0,y:133,width:780,height:455}});
  assert.deepEqual(errors,[]);console.log('BLACKSMITH_BROWSER_OK touch select/confirm, double tap, pause, reveal, refund, mobile/desktop, continuation');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
